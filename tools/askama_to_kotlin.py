#!/usr/bin/env python3
"""Translates the subset of Askama the PWA partials use into Kotlin page-builder code.

Usage: tools/askama_to_kotlin.py RUST_TEMPLATES_DIR OUT.kt partial... (e.g. pwa/_browser_settings.html)

Handled: literal text (one trailing newline dropped, as Askama does), {% if %}/{% elif %}/{% else %}/
{% endif %} over ctx.platform flags, and {{ }} for capitalize(browser), operating_system, ctx.url("/")
and h::image_tag. Anything else stops the translation, so the output is only ever complete.
"""
import re, sys

def kt_string(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$').replace('\n', '\\n') + '"'

def camel(name):
    head, *rest = name.split('_')
    return head + ''.join(w.capitalize() for w in rest)

def condition(expr):
    out = re.sub(r'ctx\.platform\.(\w+)', lambda m: 'pl.' + camel(m.group(1)), expr.strip())
    if re.search(r'[a-z_]+::|ctx\.(?!platform)', out):
        raise SystemExit(f'unsupported condition: {expr}')
    return out

def attrs(chain):
    pairs, size = [], None
    for name, args in re.findall(r'\.(\w+)\(([^()]*)\)', chain):
        if name == 'aria_hidden':
            pairs.append(('aria-hidden', 'true'))
        elif name == 'size':
            size = args.strip()
        elif name in ('class', 'alt'):
            pairs.append((name, args.strip().strip('"')))
        elif name == 'attr':
            key, value = [a.strip() for a in args.split(',', 1)]
            pairs.append((key.strip('"'), value.strip('"')))
        else:
            raise SystemExit(f'unsupported attr {name}')
    body = ', '.join(f'{kt_string(k)} to {kt_string(v)}' for k, v in pairs)
    return f'listOf({body})', (kt_string(size) if size else 'null')

def expression(expr):
    expr = expr.strip()
    if expr == 'h::capitalize(ctx.platform.browser.as_str())':
        return 'h(capitalize(pl.browser))'
    if expr == 'ctx.platform.operating_system':
        return 'h(pl.operatingSystem)'
    if expr == 'ctx.url("/")':
        return 'h(ctx.baseUrl + "/")'
    m = re.fullmatch(r'h::image_tag\(ctx, "([^"]+)", h::attrs\(\)(.*)\)', expr)
    if m:
        pairs, size = attrs(m.group(2))
        return f'imageTag({kt_string(m.group(1))}, {pairs}, {size})'
    raise SystemExit(f'unsupported expression: {expr}')

def translate(name, source):
    if source.endswith('\n'):
        source = source[:-1]
    lines, depth = [], 1
    for token in re.split(r'(\{%.*?%\}|\{\{.*?\}\}|\{#.*?#\})', source, flags=re.S):
        if not token:
            continue
        indent = '    ' * depth
        if token.startswith('{#'):
            continue
        if token.startswith('{%'):
            tag = token[2:-2].strip()
            if tag.startswith('if '):
                lines.append(f'{indent}if ({condition(tag[3:])}) {{'); depth += 1
            elif tag.startswith('elif '):
                lines.append(f'{"    " * (depth - 1)}}} else if ({condition(tag[5:])}) {{')
            elif tag == 'else':
                lines.append(f'{"    " * (depth - 1)}}} else {{')
            elif tag == 'endif':
                depth -= 1; lines.append(f'{"    " * depth}}}')
            else:
                raise SystemExit(f'unsupported tag: {tag}')
        elif token.startswith('{{'):
            lines.append(f'{indent}p.append({expression(token[2:-2])})')
        else:
            lines.append(f'{indent}p.append({kt_string(token)})')
    fn = camel(re.sub(r'[^a-z_]', '_', name.replace('.html', '').replace('/', '_').replace('pwa__', 'pwa_')).strip('_'))
    body = '\n'.join(lines)
    return f'''/** `{name}`, translated from the Rust port's Askama template by tools/askama_to_kotlin.py. */
internal fun {fn}(p: PageParts.Builder, ctx: LayoutContext, pl: Platform) {{
{body}
}}
'''

def main():
    root, out, names = sys.argv[1], sys.argv[2], sys.argv[3:]
    parts = ['// Generated by tools/askama_to_kotlin.py from once-campfire-rust/crates/views/templates; do not edit.\n',
             'package campfire.views\n', 'import campfire.kit.PageParts\n']
    for name in names:
        parts.append(translate(name, open(f'{root}/{name}').read()))
    open(out, 'w').write('\n'.join(parts))

main()
